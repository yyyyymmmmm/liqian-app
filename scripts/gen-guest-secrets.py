#!/usr/bin/env python3
"""生成 Sources/LiqianApp/GuestSecrets.swift（扫码随礼配发键注入，v5.12）。

键来源：环境变量 LIQIAN_ISSUE_KEY（CI 从 GitHub Actions Secret 注入；
本地联调可手动 export，值取自 liqian-guest/secrets.local.txt，勿入库）。
落盘形态：键字节先与固定掩码逐字节 XOR、再 base64——生成文件与最终
IPA 里都只有掩码后的字节串，grep 工作区/IPA 找不到键明文（验收口径）。
无键时写占位文件（isPlaceholder=true），App 侧据此优雅降级「暂未开通」，
保证 fork/本地无键构建照样编译通过。

本脚本绝不打印键值，只打印形态信息。
"""
import base64
import os
import sys

MASK = b"liqian-guest-v1-mask"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "Sources", "LiqianApp", "GuestSecrets.swift")

key = os.environ.get("LIQIAN_ISSUE_KEY", "").strip()
if key:
    raw = key.encode("utf-8")
    masked = bytes(b ^ MASK[i % len(MASK)] for i, b in enumerate(raw))
    b64 = base64.b64encode(masked).decode("ascii")
    placeholder = "false"
else:
    b64 = ""
    placeholder = "true"

content = f"""// GENERATED by scripts/gen-guest-secrets.py — 请勿手改、请勿提交（已在 .gitignore）。
// liqian-guest 配发键的掩码形态：字节已 XOR 掩码＋base64，键明文不在此文件。
// marker: liqian-guest-key-v1
enum GuestSecrets {{
    static let encodedIssueKeyBase64 = "{b64}"
    static let isPlaceholder = {placeholder}
}}
"""

with open(OUT, "w", encoding="utf-8") as f:
    f.write(content)
print(f"GuestSecrets.swift written (placeholder={placeholder}, masked_b64_chars={len(b64)})")
sys.exit(0)
